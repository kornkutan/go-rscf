func TestRunFixWritesAndStaysGofmtClean(t *testing.T) {
	dir := t.TempDir()
	src := "package x\n\n// CreateOrder creates an order.\nfunc CreateOrder() {}\n"
	p := writeFile(t, dir, "a.go", src)

	code, out, _ := runCLI(t, "--fix", dir)
	if code != 1 {
		t.Errorf("exit = %d, want 1 (PURPOSE placeholder stays report-only)", code)
	}
	if !strings.Contains(out, "fixed ") {
		t.Errorf("missing fixed line, got: %s", out)
	}
	got, err := os.ReadFile(p)
	if err != nil {
		t.Fatal(err)
	}
	if strings.Contains(string(got), "CreateOrder creates") {
		t.Errorf("comment not deleted: %s", got)
	}
	if !strings.Contains(string(got), "/// <!- FILE: `a.go`") {
		t.Errorf("heading not injected: %s", got)
	}
	assertGofmtClean(t, got)

	// Second run: fixable work is done; only the PURPOSE placeholder remains.
	code2, out2, _ := runCLI(t, "--fix", dir)
	if code2 != 1 {
		t.Errorf("second run exit = %d, want 1 (placeholder)", code2)
	}
	if !strings.Contains(out2, "replace TODO placeholder") {
		t.Errorf("second run missing placeholder report, got: %s", out2)
	}
}

