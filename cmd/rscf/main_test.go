func TestCollectFiles(t *testing.T) {
	dir := t.TempDir()
	writeFile(t, dir, "a.go", "package a\n")
	writeFile(t, dir, "sub/b.go", "package b\n")
	writeFile(t, dir, "sub/deep/c.go", "package c\n")
	writeFile(t, dir, "vendor/v.go", "package v\n")
	writeFile(t, dir, "testdata/t.go", "package t\n")
	writeFile(t, dir, "bin/x.go", "package x\n")
	writeFile(t, dir, "notes.txt", "not go")

	var errb bytes.Buffer
	files := collectFiles([]string{dir}, &errb)
	names := map[string]bool{}
	for _, f := range files {
		names[filepath.Base(f)] = true
	}
	for _, want := range []string{"a.go", "b.go", "c.go"} {
		if !names[want] {
			t.Errorf("missing %s in collected files: %v", want, files)
		}
	}
	for _, no := range []string{"v.go", "t.go", "x.go"} {
		if names[no] {
			t.Errorf("%s should be skipped: %v", no, files)
		}
	}

	// Single .go file arg.
	single := collectFiles([]string{filepath.Join(dir, "a.go")}, &errb)
	if len(single) != 1 || filepath.Base(single[0]) != "a.go" {
		t.Errorf("single file arg: got %v", single)
	}
	// Non-.go file arg is ignored.
	none := collectFiles([]string{filepath.Join(dir, "notes.txt")}, &errb)
	if len(none) != 0 {
		t.Errorf("non-.go file should be ignored: %v", none)
	}
	// Stat error path.
	_ = collectFiles([]string{"/no/such/path"}, &errb)
	if !strings.Contains(errb.String(), "stat /no/such/path") {
		t.Errorf("missing stat error on stderr, got: %s", errb.String())
	}
}

func TestRel(t *testing.T) {
	cwd, _ := os.Getwd()
	if got := rel("./x.go"); got != "x.go" {
		t.Errorf("rel(./x.go) = %q, want x.go", got)
	}
	if got := rel(filepath.Join(cwd, "sub", "x.go")); got != filepath.Join("sub", "x.go") {
		t.Errorf("rel(under cwd) = %q", got)
	}
	if got := rel("/elsewhere/x.go"); got != "/elsewhere/x.go" {
		t.Errorf("rel(outside cwd) = %q, want unchanged", got)
	}
}

func assertGofmtClean(t *testing.T, src []byte) {
	t.Helper()
	formatted, err := format.Source(src)
	if err != nil {
		t.Errorf("gofmt parse error: %v", err)
		return
	}
	if string(formatted) != string(src) {
		t.Errorf("source is not gofmt-clean\nGOT:\n%s\nFMT:\n%s", src, formatted)
	}
}
